const TERMS_BY_ID = new Map(GLOSSARY_TERMS.map((entry) => [entry.id, entry]));

/** Looks up a glossary entry by id. Returns null for an unknown id rather
 * than throwing -- callers (tooltips, "Learn more" links) must fail safely
 * if a referenced id is ever renamed/removed, never crash the surface that
 * referenced it. */
export function getGlossaryTerm(id: string): GlossaryTermEntry | null {
  return TERMS_BY_ID.get(id) ?? null;
}

export function getGlossaryCategory(id: GlossaryCategoryId): GlossaryCategory | undefined {
  return GLOSSARY_CATEGORIES.find((c) => c.id === id);
}

/** Terms in a category, alphabetical by term name. */
export function termsInCategory(category: GlossaryCategoryId): GlossaryTermEntry[] {
  return GLOSSARY_TERMS.filter((entry) => entry.category === category).sort((a, b) =>
    a.term.localeCompare(b.term),
  );
}

/**
 * Matches full term, abbreviation, aliases, AND definition text (e.g. "bad
 * excursion" matching MAE's shortDefinition) -- a case-insensitive substring
 * search, not just a prefix match on the term name.
 */
export function searchGlossary(query: string): GlossaryTermEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return GLOSSARY_TERMS.filter((entry) => {
    const haystacks = [
      entry.term,
      entry.abbreviation ?? "",
      ...(entry.aliases ?? []),
      entry.shortDefinition,
      entry.whyItMatters,
      entry.howDeskUsesIt,
    ];
    return haystacks.some((h) => h.toLowerCase().includes(q));
  }).sort((a, b) => a.term.localeCompare(b.term));
}
