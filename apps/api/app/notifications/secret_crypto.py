"""Phase 20.1 -> Phase 20.2: symmetric encryption for one secret -- a
user's own Pushover User Key -- at rest. The only reversible-secret
storage in this codebase (passwords use bcrypt, one-way, see
app.auth.security; this needs to be reversible because the plaintext key
must be sent to Pushover's API on every push).

Phase 20.2 operational-security fix: this previously derived its Fernet
key from `settings.secret_key` (the JWT/session signing secret) to avoid
introducing a new environment variable. That coupled two unrelated
concerns -- rotating SECRET_KEY (an ordinary, expected session-security
operation) would silently make every already-stored Pushover user key
undecryptable, with no error until the next push attempt quietly no-ops.
This module now takes a DEDICATED `encryption_key` (sourced from the new
`PUSHOVER_KEY_ENCRYPTION_KEY` environment variable, see app.config and
app.alerts.push) that has nothing to do with session signing -- rotating
one never affects the other.

`encryption_key` may be an already Fernet-compatible secret (32 raw bytes,
urlsafe-base64-encoded -- e.g. one generated by `Fernet.generate_key()`)
or any other non-empty string, which is safely transformed into one via
SHA-256 (scoped by a fixed, distinct context string, so this derivation
can never collide with any other use of the same raw value elsewhere in
the codebase). Either way, changing the configured value makes any
ciphertext encrypted under the old value permanently undecryptable by
design -- callers must treat `decrypt_secret` returning None as "no key
configured," never as an error to propagate.

This is a minimal, no-new-infrastructure approach, not a KMS/envelope-
encryption system -- the codebase has no existing encryption-at-rest
abstraction to reuse (confirmed by inspection), and introducing one would
be materially larger than this feature warrants. Real key-rotation/
HSM-backed storage is a separate, larger piece of work -- documented here
as a known limitation, not silently assumed away.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
from typing import Optional

from cryptography.fernet import Fernet, InvalidToken

_KEY_DERIVATION_CONTEXT = "ai-market-desk:pushover-user-key-encryption:v2"


def _coerce_fernet_key(encryption_key: str) -> bytes:
    """If `encryption_key` is already a valid Fernet key (32 raw bytes,
    urlsafe-base64-encoded), use it directly -- otherwise safely derive
    one via SHA-256. Accepts either shape so an operator can configure
    either a real `Fernet.generate_key()` value or any other sufficiently
    random string without this module rejecting one of the two forms."""
    candidate = encryption_key.encode("utf-8")
    try:
        decoded = base64.urlsafe_b64decode(candidate)
    except (ValueError, binascii.Error):
        decoded = None
    if decoded is not None and len(decoded) == 32:
        return candidate
    digest = hashlib.sha256(f"{_KEY_DERIVATION_CONTEXT}:{encryption_key}".encode()).digest()
    return base64.urlsafe_b64encode(digest)


def encrypt_secret(plaintext: str, *, encryption_key: str) -> str:
    """Never logs or echoes `plaintext` or `encryption_key` -- callers
    must not either."""
    token = Fernet(_coerce_fernet_key(encryption_key)).encrypt(plaintext.encode("utf-8"))
    return token.decode("utf-8")


def decrypt_secret(ciphertext: str, *, encryption_key: str) -> Optional[str]:
    """Returns None (never raises) for a malformed or undecryptable
    token -- e.g. `PUSHOVER_KEY_ENCRYPTION_KEY` changed since this was
    encrypted -- so a caller can treat it the same as "no key configured"
    rather than crashing the monitoring loop."""
    try:
        token = Fernet(_coerce_fernet_key(encryption_key)).decrypt(ciphertext.encode("utf-8"))
    except (InvalidToken, ValueError):
        return None
    return token.decode("utf-8")
